#!/usr/bin/env python3
"""Derive camera menu font coverage facts from the original C3.11 MAIN payload.

Writes two generated files from the ROM (code points and record locations
only; no glyph data):
  z8photolut/src/fonts.h          cmap record location/count per ROM font (firmware)
  resources/photo-lut-fonts.json  covered code-point ranges of the label fonts (host)

The 24 ROM fonts are listed at 0x42dec310 (pointers) and 0x42dec3d0 (sizes).
In each font, the u32 at +0x28 locates its code-point map: a u32 record
count, zero padding, then byte-packed {u16 first code point, u16 first glyph,
u16 count} records in increasing, non-overlapping order (the last may be a
sentinel). The layout is reverse-engineered; check_coverage() validates it
against every code point the stock menus of the CJK languages use.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct

ROM_SHA256 = '2b43a31c9de838f84b12416de4348a7004e65be07f853ec56ec2b10f3a8e3853'
BASE, FONT_POINTERS, FONT_SIZES, FONTS = 0x40160000, 0x42dec310, 0x42dec3d0, 24
DIRECTORY, BLOBS, CLASS_MAP, STRINGS = 0x4327c5a0, 0x439daf58, 0x4320a3cc, 3137
# Per-string font overrides {u16 id, u8 font, u8 0, u32 language} (language names).
OVERRIDES, OVERRIDE_COUNT = 0x42ad76b4, 30
# Fonts the firmware may choose for photo LUT labels: the class-0 menu font
# of English (16), Simplified (2) and Traditional Chinese (0), Japanese (13)
# and Korean (22), queried by language through the stock resolver.
LABEL_FONTS = (16, 2, 0, 13, 22)
UI_FONT = {0: 13, 8: 2, 9: 0, 10: 22}          # stock class-0 font of these UI languages


def u32(rom, va):
    return struct.unpack_from('<I', rom, va-BASE)[0]


def u64(rom, va):
    return struct.unpack_from('<Q', rom, va-BASE)[0]


def cmap(rom, font):
    """(records VA, [(first, glyph, count)]) of one ROM font."""
    start, size = u64(rom, FONT_POINTERS+8*font), u32(rom, FONT_SIZES+4*font)
    blob = rom[start-BASE:start-BASE+size]
    area = struct.unpack_from('<I', blob, 0x28)[0]
    for header in range(area, area+0x48):
        for padding in (0, 2, 4):
            count, at = struct.unpack_from('<I', blob, header)[0], header+4+padding
            if not 1 <= count <= 8000 or any(blob[header+4:at]) or at+6*count > len(blob):
                continue
            records = [struct.unpack_from('<3H', blob, at+6*k) for k in range(count)]
            valid = 0
            for k, (first, _, run) in enumerate(records):
                if not run or (k and first < records[k-1][0]+records[k-1][2]):
                    break
                valid += 1
            if valid >= count-1 and valid:
                return start+at, records[:valid]
    raise ValueError(f'No code-point map in ROM font {font}')


def stock_strings(rom, language):
    """Stock strings drawn with the class-0 font (the class of every photo LUT label)."""
    table, blob = u64(rom, DIRECTORY+8*language)-BASE, u64(rom, BLOBS+8*language)-BASE
    offsets = struct.unpack_from(f'<{STRINGS}i', rom, table)
    classes = rom[CLASS_MAP-BASE:CLASS_MAP-BASE+STRINGS]
    overridden = {struct.unpack_from('<H', rom, OVERRIDES-BASE+8*k)[0] for k in range(OVERRIDE_COUNT)}
    for string, (start, end, kind) in enumerate(zip(offsets, offsets[1:], classes)):
        if 0 <= start < end and kind == 0 and string not in overridden:
            yield rom[blob+start:blob+end].decode('utf-16le', 'replace')


def covered(records, code):
    return any(first <= code < first+run for first, _, run in records)


def check_coverage(rom, maps):
    """Every non-control, non-private code point of a CJK menu's class-0 strings is in its font."""
    for language, font in UI_FONT.items():
        used = {ord(c) for text in stock_strings(rom, language) for c in text
                if ord(c) >= 0x20 and not 0xe000 <= ord(c) < 0xf900 and c != '�'}
        missing = sorted(c for c in used if not covered(maps[font][1], c))
        if missing:
            raise ValueError(f'Font {font} map misses {len(missing)} code points of language {language}')


def derive(rom):
    if hashlib.sha256(rom).hexdigest() != ROM_SHA256:
        raise ValueError('Original C3.11 MAIN payload required')
    maps = [cmap(rom, font) for font in range(FONTS)]
    check_coverage(rom, maps)
    return maps


def header(maps):
    rows = [f'    {{0x{va:08x}u, {len(records):4}u}}, /* font {i:2} */' for i, (va, records) in enumerate(maps)]
    return ('/* SPDX-License-Identifier: GPL-3.0-or-later */\n'
            '/* Generated by tools/photo_lut_fonts.py from the original C3.11 MAIN payload. Byte-packed\n'
            ' * {u16 first code point, u16 first glyph, u16 count} records of each ROM font, sorted. */\n'
            '#ifndef Z8_PHOTO_LUT_FONTS_H\n#define Z8_PHOTO_LUT_FONTS_H\n#include <stdint.h>\n'
            '#define Z8_ROM_FONTS 24u\n'
            'static const struct { uint32_t records,count; } z8_rom_fonts[Z8_ROM_FONTS]={\n'
            + '\n'.join(rows) + '\n};\n#endif\n')


def ranges(maps):
    fonts = {}
    for font in LABEL_FONTS:
        merged = []
        for first, _, run in maps[font][1]:
            if merged and merged[-1][1] == first:
                merged[-1][1] = first+run
            else:
                merged.append([first, first+run])
        fonts[str(font)] = merged
    return dict(schema=1, source='C3.11 MAIN payload '+ROM_SHA256, label_fonts=list(LABEL_FONTS),
                note='Covered code points [first, end) of the camera menu fonts photo LUT labels can use. '
                     'A label draws without boxes only if one of these fonts covers all of its characters.',
                fonts=fonts)


def encode_ranges(data):
    """Stable, reviewable JSON: one line per font."""
    fonts = ',\n'.join(f'  "{k}": {json.dumps(v, separators=(",", ":"))}' for k, v in data['fonts'].items())
    head = {k: v for k, v in data.items() if k != 'fonts'}
    return json.dumps(head, indent=1, ensure_ascii=False)[:-2]+',\n "fonts": {\n'+fonts+'\n }\n}\n'


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('rom', type=Path, help='Original C3.11 main payload (z8-main-payload.bi)')
    p.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    a = p.parse_args()
    maps = derive(a.rom.read_bytes())
    (a.root/'z8photolut/src/fonts.h').write_text(header(maps))
    (a.root/'resources/photo-lut-fonts.json').write_text(encode_ranges(ranges(maps)))


if __name__ == '__main__':
    main()
